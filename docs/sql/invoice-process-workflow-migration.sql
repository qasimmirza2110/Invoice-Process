-- Approval gates - each one needs the owner's separate approval, in this order:
--   L-A  Fresh pg_dump of the database (record exit code and size), restore it into a NEW scratch database,
--        run PART 1 on both and compare. Then this script on the scratch database only, then PART 3 on scratch.
--   L-A  App validation on scratch: start the app against the scratch database with INVOICE_DB_URL,
