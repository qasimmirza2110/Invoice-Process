  AND table_name IN ('app_users', 'categories', 'reviewer_categories', 'upload_batches', 'extraction_jobs',
                     'gemini_call_attempts', 'invoice_review_reasons', 'invoice_workflow_events')
ORDER BY table_name;
SELECT (SELECT count(*) FROM public.app_users)               AS app_users,
       (SELECT count(*) FROM public.categories)              AS categories,
       (SELECT count(*) FROM public.reviewer_categories)     AS reviewer_categories,
       (SELECT count(*) FROM public.upload_batches)          AS upload_batches,
       (SELECT count(*) FROM public.extraction_jobs)         AS extraction_jobs,
       (SELECT count(*) FROM public.gemini_call_attempts)    AS gemini_call_attempts,
       (SELECT count(*) FROM public.invoice_review_reasons)  AS invoice_review_reasons,
       (SELECT count(*) FROM public.invoice_workflow_events) AS invoice_workflow_events;

