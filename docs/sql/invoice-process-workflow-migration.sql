-- Did it commit? If the session was interrupted, check before doing anything else:
--     SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'app_users';
-- 1 = the migration committed (do NOT run it again); 0 = nothing was applied (the whole script is one transaction).
--
-- Everything is ADDITIVE: new tables + new nullable columns on invoices. No existing row is changed; legacy
-- invoices keep NULL owner/batch and stay ADMIN-only. Rollback = stop the app / disable the worker; do NOT drop
-- these tables once workflow data exists (that would destroy users, jobs, audit events and approvals).
--
-- The checks below never print invoice content: only counts and md5 digests.
