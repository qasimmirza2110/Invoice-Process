-- ---------------------------------------------------------------- Part B: read-only verification queries

-- B1. Did the schema change happen, and is it the expected shape?
SELECT table_name, column_name, data_type, is_nullable
FROM information_schema.columns
WHERE (table_name IN ('invoice_documents', 'invoice_versions'))
   OR (table_name = 'invoices' AND column_name = 'source_document_id')
ORDER BY table_name, ordinal_position;

SELECT conname, contype, pg_get_constraintdef(oid) AS definition
FROM pg_constraint
WHERE conname IN ('uk_invoice_versions_invoice_version', 'fk_invoice_versions_invoice',
                  'fk_invoice_versions_source_document', 'fk_invoices_source_document');

-- B2. Row counts (compare with the counts taken before the first start: invoices/invoice_items must be unchanged).
SELECT (SELECT count(*) FROM invoices)          AS invoices,
       (SELECT count(*) FROM invoice_items)     AS invoice_items,
       (SELECT count(*) FROM invoice_versions)  AS invoice_versions,
       (SELECT count(*) FROM invoice_documents) AS invoice_documents;

-- B3. Versions per invoice, with provenance.
SELECT invoice_id,
       count(*)                                         AS versions,
       max(version_number)                              AS current_version,
       string_agg(change_source, ' > ' ORDER BY version_number) AS history
FROM invoice_versions
GROUP BY invoice_id
ORDER BY invoice_id;

-- B4. Version numbers must be 1..N without gaps for every invoice (expect no rows).
SELECT invoice_id, count(*) AS versions, max(version_number) AS max_version
FROM invoice_versions
GROUP BY invoice_id
HAVING count(*) <> max(version_number) OR min(version_number) <> 1;

-- B5. The current projection must equal the latest snapshot: item count (expect no rows).
SELECT v.invoice_id, jsonb_array_length(v.snapshot_data -> 'items') AS snapshot_items, count(ii.id) AS current_items
FROM invoice_versions v
LEFT JOIN invoice_items ii ON ii.invoice_id = v.invoice_id
WHERE v.version_number = (SELECT max(v2.version_number) FROM invoice_versions v2 WHERE v2.invoice_id = v.invoice_id)
GROUP BY v.invoice_id, v.snapshot_data
HAVING jsonb_array_length(v.snapshot_data -> 'items') <> count(ii.id);

-- B6. ... and header values (expect no rows).
SELECT i.id, i.invoice_number, v.snapshot_data ->> 'invoiceNumber' AS snapshot_number,
       i.total_amount, v.snapshot_data ->> 'totalAmount' AS snapshot_total
FROM invoices i
JOIN invoice_versions v ON v.invoice_id = i.id
WHERE v.version_number = (SELECT max(v2.version_number) FROM invoice_versions v2 WHERE v2.invoice_id = i.id)
  AND (i.invoice_number IS DISTINCT FROM v.snapshot_data ->> 'invoiceNumber'
       OR i.total_amount IS DISTINCT FROM (v.snapshot_data ->> 'totalAmount')::numeric);

-- B7. Every version of an invoice points at the same source PDF as the invoice (expect no rows).
SELECT v.invoice_id, v.version_number, v.source_document_id, i.source_document_id AS invoice_document
FROM invoice_versions v
JOIN invoices i ON i.id = v.invoice_id
WHERE v.source_document_id IS DISTINCT FROM i.source_document_id;

-- B8. Source PDF status per invoice (legacy invoices have none - that is expected and honest).
SELECT i.id, i.status, i.source_file_name, d.id AS document_id, d.sha256, d.size_bytes, d.created_at
FROM invoices i
LEFT JOIN invoice_documents d ON d.id = i.source_document_id
ORDER BY i.id;

-- B9. Legacy baselines: invoices whose V1 is NOT an original extraction.
SELECT invoice_id, version_number, created_at, change_reason
FROM invoice_versions
WHERE change_source = 'LEGACY_BASELINE'
ORDER BY invoice_id;

-- B10. Orphan check: document rows not used by any invoice (expect none after normal operation).
--      Files in the storage folder WITHOUT a row are listed by comparing the folder with:  SELECT id FROM invoice_documents;
SELECT d.id, d.created_at
FROM invoice_documents d
WHERE NOT EXISTS (SELECT 1 FROM invoices i WHERE i.source_document_id = d.id);
