-- =====================================================================================================
-- Invoice Process - editable extraction + immutable version history: schema reference and READ-ONLY checks
-- =====================================================================================================
--
-- HOW THE SCHEMA IS CREATED
--   These objects were originally added by Hibernate (ddl-auto=update) during development. The application now
--   runs with ddl-auto=validate and never changes a schema itself. A database that does not have these objects
--   yet needs them created by a reviewed script, after a restore-tested backup, BEFORE the application starts.
--   They ONLY ADD: 2 new tables, 1 new NULLABLE column on invoices, constraints.
--
--   Part A is the DDL as Hibernate produced it on the isolated TEST database (pg_dump --schema-only, 2026-10-16).
--   It is documentation, commented out on purpose.
--
-- BEFORE CREATING THEM ON A NON-TEST DATABASE (requires separate approval):
--   1. fresh pg_dump of that database (record exit code and size)
--   2. restore-test that dump into a separate scratch database and compare row counts
--   3. create the objects on the scratch copy first, then validate the application against it.
--
-- B6 and B8 below show invoice numbers, amounts and file names for the rows they list: run them only locally,
-- never paste their output anywhere.
-- Part B queries are SELECT-only. Nothing in this file deletes, truncates, drops or updates data.
-- =====================================================================================================


-- ---------------------------------------------------------------- Part A: schema reference (documentation)

